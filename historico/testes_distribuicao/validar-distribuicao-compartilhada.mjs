import fs from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

const modulo = process.env.PGLITE_MODULE
if (!modulo) throw new Error('Defina PGLITE_MODULE com o caminho do PGlite.')
const { PGlite } = await import(pathToFileURL(modulo).href)
const db = new PGlite()

const admin = '00000000-0000-4000-8000-000000000001'
const analistaA = '00000000-0000-4000-8000-000000000002'
const analistaB = '00000000-0000-4000-8000-000000000003'

await db.exec(`
  create schema auth;
  create function auth.uid() returns uuid language sql stable as
    $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  create role anon; create role authenticated;
  create table public.perfis (id uuid primary key, nome text not null, perfil text not null, ativo boolean not null);
  create table public.distribuicoes (
    id bigint generated by default as identity primary key,
    analista_id uuid not null references public.perfis(id), municipio text, tipo text,
    similaridade_minima numeric(5,2) not null default 0, ativo boolean not null default true,
    criado_por uuid not null references public.perfis(id), criado_em timestamptz not null default now(),
    atualizado_em timestamptz not null default now()
  );
  insert into public.perfis values
    ('${admin}','Admin','admin',true), ('${analistaA}','A','analista',true), ('${analistaB}','B','analista',true);
  set request.jwt.claim.sub = '${admin}';
`)

await db.exec(await fs.readFile(new URL('../sql/PERMITIR_MUNICIPIO_COMPARTILHADO.sql', import.meta.url), 'utf8'))
await db.query(`select public.salvar_distribuicao_web($1, 'SÃO JOSÉ DOS CAMPOS', null, 80)`, [analistaA])
await db.query(`select public.salvar_distribuicao_web($1, 'SÃO JOSÉ DOS CAMPOS', null, 80)`, [analistaB])

const { rows } = await db.query(`select count(*)::int total from public.distribuicoes where municipio='SÃO JOSÉ DOS CAMPOS'`)
if (rows[0].total !== 2) throw new Error('O mesmo município não foi liberado para os dois analistas.')

let duplicataBloqueada = false
try {
  await db.query(`select public.salvar_distribuicao_web($1, 'SÃO JOSÉ DOS CAMPOS', null, 80)`, [analistaA])
} catch (erro) {
  duplicataBloqueada = String(erro).includes('já possui este mesmo recorte')
}
if (!duplicataBloqueada) throw new Error('Regra duplicada do mesmo analista deveria ser recusada.')

console.log('Distribuição compartilhada validada: dois analistas no mesmo município; duplicata individual bloqueada.')
await db.close()
