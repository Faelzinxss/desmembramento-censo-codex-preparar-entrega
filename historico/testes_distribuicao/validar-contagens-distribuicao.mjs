import fs from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

const modulo = process.env.PGLITE_MODULE
if (!modulo) throw new Error('Defina PGLITE_MODULE com o caminho do PGlite.')
const { PGlite } = await import(pathToFileURL(modulo).href)
const db = new PGlite()
const admin = '00000000-0000-4000-8000-000000000001'
const analista = '00000000-0000-4000-8000-000000000002'

await db.exec(`
  create schema auth;
  create function auth.uid() returns uuid language sql stable as
    $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  create role anon; create role authenticated;
  create table public.perfis (id uuid primary key, nome text, perfil text, ativo boolean);
  create table public.casos (
    caso_id text primary key, ativo boolean, similaridade numeric, tipo text,
    municipio_a text, municipio_b text
  );
  create table public.revisoes (caso_id text primary key);
  create table public.reservas (caso_id text primary key, expira_em timestamptz);
  create table public.distribuicoes (
    id bigint generated by default as identity primary key, analista_id uuid,
    municipio text, tipo text, similaridade_minima numeric, ativo boolean
  );
  insert into public.perfis values ('${admin}','Admin','admin',true), ('${analista}','Analista','analista',true);
  insert into public.casos values
    ('apiaí-pendente',true,90,'Duplicidade','APIAÍ',null),
    ('apiaí-concluido',true,85,'Duplicidade','APIAÍ',null),
    ('fora-do-recorte',true,99,'Duplicidade','OUTRO',null);
  insert into public.revisoes values ('apiaí-concluido');
  insert into public.distribuicoes (analista_id,municipio,tipo,similaridade_minima,ativo)
    values ('${analista}','APIAÍ',null,80,true);
  create function public.casos_autorizados_web() returns table(caso_id text)
  language sql stable security definer set search_path=public as $$
    select c.caso_id from public.casos c join public.perfis p on p.id=auth.uid() and p.ativo
    where c.ativo and (p.perfil='admin' or exists (
      select 1 from public.distribuicoes d where d.analista_id=p.id and d.ativo
        and (d.municipio is null or d.municipio=c.municipio_a or d.municipio=c.municipio_b)
        and (d.tipo is null or d.tipo=c.tipo) and c.similaridade>=d.similaridade_minima
    ));
  $$;
`)

await db.exec(await fs.readFile(new URL('../sql/CORRIGIR_CONTAGENS_DISTRIBUICAO.sql', import.meta.url), 'utf8'))
await db.exec(`set request.jwt.claim.sub = '${analista}'`)
const resumoAnalista = (await db.query(`select public.resumo_fila_web() resumo`)).rows[0].resumo
const pendentesAnalista = (await db.query(`select public.contar_fila_filtrada_web('Pendente',null,null,0) total`)).rows[0].total
if (resumoAnalista.total !== 2 || resumoAnalista.concluidos !== 1 || resumoAnalista.pendentes !== 1 || Number(pendentesAnalista) !== 1) {
  throw new Error(`Contagem do analista incorreta: ${JSON.stringify({ resumoAnalista, pendentesAnalista })}`)
}

await db.exec(`set request.jwt.claim.sub = '${admin}'`)
const resumoAdmin = (await db.query(`select public.resumo_fila_web() resumo`)).rows[0].resumo
if (resumoAdmin.total !== 3) throw new Error(`Administrador deveria ver 3 casos: ${JSON.stringify(resumoAdmin)}`)

console.log('Contagens validadas: analista vê somente seu município e administrador mantém visão completa.')
await db.close()
